TICK_HZ = 100000

@dataclass
class Task:
    name: str
    period: float
    priority: int
    deadline: float = None
    stack: int = 256
    phase: float = 0
    wcet: float = None

    def __post_init__(self):
        if self.deadline is None:
            self.deadline = self.period


def load(path):
    raw = yaml.safe_load(Path(path).read_text())
    sched = raw.get("scheduler", {}) or {}
    tasks = [
        Task(
            name=t["name"], period=t["period_ms"], priority=t["priority"],
            deadline=t.get("deadline_ms"), stack=t.get("stack_words", 256),
            phase=t.get("phase_ms", 0), wcet=t.get("wcet_ms"),
        )
        for t in raw["tasks"]
    ]
    policy = sched.get("policy", "SKIP")
    return tasks, {
        "policy": policy,
        "max_tasks": sched.get("max_tasks", 8),
        "trace": sched.get("trace_enabled", True),
    }


def to_ticks(tasks, tick_hz):
    for t in tasks:
        t.period = math.floor(t.period * tick_hz / 1000)
        t.deadline = math.floor(t.deadline * tick_hz / 1000)
        if t.wcet is not None:
            t.wcet = math.ceil(t.wcet * tick_hz / 1000)


def response_time(task, higher):
    w = task.wcet
    while True:
        w_next = task.wcet + sum(math.ceil(w / h.period) * h.wcet for h in higher)
        if w_next == w or w_next > task.deadline:
            return w_next
        
        w = w_next


def analyze(tasks, tick_hz):
    to_ticks(tasks, tick_hz)

    print(f"tick_hz = {tick_hz}  (1 tick = {1000 / tick_hz:.3f} ms)")
    print(f"{'task':<16}{'T(tick)':>8}{'D(tick)':>8}{'C(tick)':>8}{'R(tick)':>8}  result")

    ok = True
    for t in tasks:
        higher = [h for h in tasks if h.priority > t.priority]
        r = response_time(t, higher)
        passed = r <= t.deadline
        ok &= passed
        print(f"{t.name:<16}{t.period:>8}{t.deadline:>8}{t.wcet:>8}{r:>8}  {'OK' if passed else 'MISS'}")

    print("SCHEDULABLE" if ok else "NOT SCHEDULABLE")
    return ok


