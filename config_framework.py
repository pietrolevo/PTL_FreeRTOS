def generate(tasks, cfg, out_dir):
    out = Path(out_dir)
    (out / "src").mkdir(parents=True, exist_ok=True)
    (out / "include").mkdir(parents=True, exist_ok=True)

    configs = "\n".join(CFG.format(n=t.name, stack=t.stack, priority=t.priority, period=t.period, deadline=t.deadline, phase=t.phase) for t in tasks)
    creates = "\n".join(f"    xPTL_CreateTask( &x{t.name}Cfg, NULL );" for t in tasks)

    (out / "src" / "main.c").write_text(MAIN_C.format(
        max_tasks=cfg["max_tasks"], policy=cfg["policy"],
        trace="pdTRUE" if cfg["trace"] else "pdFALSE", configs=configs, creates=creates))

    protos = "\n".join(f"void v{t.name}Task( void *pArg );" for t in tasks)
    (out / "include" / "tasks.h").write_text(
        f'#ifndef TASKS_H\n#define TASKS_H\n\n#include "FreeRTOS.h"\n#include "task.h"\n\n{protos}\n#endif\n')

    tasks_c = out / "src" / "tasks.c"
    if not tasks_c.exists():
        stubs = "\n".join(STUB.format(n=t.name) for t in tasks)
        tasks_c.write_text(f'#include "tasks.h"\n#include "ptl.h"\n\n{stubs}')

    (out / "include" / "FreeRTOSConfig.h").write_text(
        FREERTOS_CONFIG_H.format(tick_hz=TICK_HZ))

    print(f"generated in {out}/")


def main():
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)

    a = sub.add_parser("analyze")
    a.add_argument("file")

    g = sub.add_parser("generate")
    g.add_argument("file")
    g.add_argument("-o", "--output", default="generated")

    args = p.parse_args()
    tasks, cfg = load(args.file)

    if args.cmd == "analyze":
        sys.exit(0 if analyze(tasks, TICK_HZ) else 1)
    else:
        generate(tasks, cfg, args.output)


if __name__ == "__main__":
    main()